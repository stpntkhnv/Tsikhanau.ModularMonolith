using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Tsikhanau.Monolith.ArchRules.Support;

internal static class SuppressionSyntaxExtensions
{
    private const String InactiveBranch = "in an inactive #if branch";

    private const String PragmaDisable = "#pragma warning disable";

    private const String NullableDisable = "#nullable disable";

    private const String LineHidden = "#line hidden";

    private const String SuppressMessage = "SuppressMessage";

    private const String GeneratedCode = "GeneratedCode";

    private static readonly String[] QuietingAttributeNames =
        [SuppressMessage, "UnconditionalSuppressMessage", GeneratedCode];

    private static readonly String[] QuietingAttributeWords = [SuppressMessage, GeneratedCode];

    private static readonly String[] GeneratedCodeMarkers = ["<auto-generated", "<autogenerated"];

    private static readonly SyntaxKind[] CommentKinds =
    [
        SyntaxKind.SingleLineCommentTrivia,
        SyntaxKind.MultiLineCommentTrivia,
        SyntaxKind.SingleLineDocumentationCommentTrivia,
        SyntaxKind.MultiLineDocumentationCommentTrivia,
    ];

    extension(CompilationUnitSyntax source)
    {
        public IReadOnlyList<DirectiveTriviaSyntax> SuppressingDirectives =>
        [
            .. source
                .DescendantNodes(descendIntoTrivia: true)
                .OfType<DirectiveTriviaSyntax>()
                .Where(IsSuppressing),
        ];

        public IEnumerable<SourceFinding> CollectSuppressions() =>
        [
            .. source.SuppressingDirectives.Select(directive => directive.Describe()),
            .. CollectGeneratedCodeHeaders(source),
            .. source.CollectQuietingAttributes(),
        ];

        public IEnumerable<SourceFinding> CollectQuietingAttributes() =>
        [
            .. CollectAttributes(source),
            .. CollectAttributeAliases(source),
            .. CollectAttributesInInactiveText(source),
        ];
    }

    extension(DirectiveTriviaSyntax directive)
    {
        public SourceFinding Describe() =>
            new(directive.GetLocation().StartLine, BuildDirectiveText(directive) + DescribeBranch(directive.IsActive));
    }

    private static Boolean IsSuppressing(DirectiveTriviaSyntax directive) =>
        directive switch
        {
            PragmaWarningDirectiveTriviaSyntax pragma => IsDisable(pragma.DisableOrRestoreKeyword),
            NullableDirectiveTriviaSyntax nullable => IsDisable(nullable.SettingToken),
            LineDirectiveTriviaSyntax line => line.Line.IsKind(SyntaxKind.HiddenKeyword),
            _ => false,
        };

    private static Boolean IsDisable(SyntaxToken setting) => setting.IsKind(SyntaxKind.DisableKeyword);

    private static IEnumerable<SourceFinding> CollectGeneratedCodeHeaders(CompilationUnitSyntax source) =>
        source
            .GetLeadingTrivia()
            .Where(trivia => CommentKinds.Contains(trivia.Kind()))
            .SelectMany(GetLines)
            .Where(line => HasGeneratedCodeMarker(line.Text))
            .Select(line => line with { Text = $"{line.Text} {GeneratedFileNames.MarksGeneratedCode}" });

    private static IEnumerable<SourceFinding> CollectAttributes(CompilationUnitSyntax source) =>
        source
            .DescendantNodes()
            .OfType<AttributeSyntax>()
            .Where(attribute => IsQuietingName(attribute.Name))
            .Select(DescribeAttribute);

    private static IEnumerable<SourceFinding> CollectAttributeAliases(CompilationUnitSyntax source) =>
        source
            .DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            .Where(IsQuietingAlias)
            .Select(DescribeAlias);

    private static IEnumerable<SourceFinding> CollectAttributesInInactiveText(CompilationUnitSyntax source) =>
        source
            .DescendantTrivia()
            .Where(trivia => trivia.IsKind(SyntaxKind.DisabledTextTrivia))
            .SelectMany(GetLines)
            .Where(line => NamesQuietingAttribute(line.Text))
            .Select(line => line with { Text = line.Text + DescribeBranch(isActive: false) });

    private static IEnumerable<SourceFinding> GetLines(SyntaxTrivia trivia)
    {
        var firstLine = trivia.GetLocation().StartLine;

        return trivia
            .ToFullString()
            .Split('\n')
            .Select((line, index) => new SourceFinding(firstLine + index, line.Trim()));
    }

    private static Boolean HasGeneratedCodeMarker(String text) =>
        GeneratedCodeMarkers.Any(marker => text.Contains(marker, StringComparison.OrdinalIgnoreCase));

    private static Boolean NamesQuietingAttribute(String text) =>
        QuietingAttributeWords.Any(word => text.Contains(word, StringComparison.Ordinal));

    private static Boolean IsQuietingAlias(UsingDirectiveSyntax usingDirective) =>
        usingDirective.Alias is not null && IsQuietingName(usingDirective.NamespaceOrType);

    private static Boolean IsQuietingName(TypeSyntax name) => QuietingAttributeNames.Any(name.NamesAttribute);

    private static String BuildDirectiveText(DirectiveTriviaSyntax directive) =>
        directive switch
        {
            PragmaWarningDirectiveTriviaSyntax pragma => AppendArguments(PragmaDisable, BuildCodeList(pragma)),
            NullableDirectiveTriviaSyntax nullable => AppendArguments(NullableDisable, nullable.TargetToken.ValueText),
            LineDirectiveTriviaSyntax => LineHidden,
            _ => directive.ToString(),
        };

    private static String DescribeBranch(Boolean isActive) => isActive ? "" : $" {InactiveBranch}";

    private static String BuildCodeList(PragmaWarningDirectiveTriviaSyntax pragma) =>
        String.Join(", ", pragma.ErrorCodes);

    private static String AppendArguments(String directiveText, String arguments) =>
        arguments.Length == 0 ? directiveText : $"{directiveText} {arguments}";

    private static SourceFinding DescribeAttribute(AttributeSyntax attribute) =>
        new(attribute.GetLocation().StartLine, $"[{BuildTargetText(attribute)}{attribute.Name}]");

    private static String BuildTargetText(AttributeSyntax attribute) =>
        attribute.Parent is AttributeListSyntax { Target: { } target } ? $"{target.Identifier.ValueText}: " : "";

    private static SourceFinding DescribeAlias(UsingDirectiveSyntax alias) =>
        new(alias.GetLocation().StartLine, alias.ToString());
}
